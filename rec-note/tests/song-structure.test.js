/* node rec-note/tests/song-structure.test.js
   Section and Short planning must not modify lyric text or existing timing records. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const code=fs.readFileSync(path.join(root,'song-structure-core.js'),'utf8');
const widget=fs.readFileSync(path.join(root,'song-structure-studio.js'),'utf8');
const html=fs.readFileSync(path.join(root,'lyric-sync.html'),'utf8');
const css=fs.readFileSync(path.join(root,'song-structure-studio.css'),'utf8');
const sandbox={window:{}};
vm.runInNewContext(code,sandbox);
const c=sandbox.window.RECNOTE_STRUCTURE_CORE;
assert.ok(c);
assert.equal(c.seedFor('あなたと','music-structure').length,5);
assert.equal(c.seedFor('これから','music-structure').length,6);
assert.equal(c.seedFor('これからも','music-structure').length,8);
for(const song of ['あなたと','これから','これからも']){
 const s=c.seedFor(song,'music-structure'),shorts=c.seedFor(song,'short-cut');
 assert.equal(shorts.length,2);
 for(const r of [...s,...shorts]){
  assert.ok(!c.validInterval(r.start,r.end,350,true));
  assert.equal(r.status,'draft');
  assert.equal(r.source,'ep-draft-map-v01');
 }
}
assert.equal(c.parseTime('2:21.54'),141.54);
assert.equal(c.parseTime('0:00.00'),0);
assert.equal(c.formatTime(141.54),'2:21.54');
assert.equal(c.parseTime(''),null);
assert.ok(Number.isNaN(c.parseTime('1:99.99')));
assert.ok(c.validInterval(12,11,null,true));
assert.ok(c.validInterval(null,null,null,true));
assert.ok(c.validInterval(3,13,10,true));
assert.equal(c.validInterval(3,9,10,true),'');
const e={id:'s1',song:'あなたと',start:80.79,end:118.53,label:'サビ1'};
const cut=c.clipFromSection(e);
assert.equal(cut.start,80.79);
assert.equal(cut.end,105.79);
assert.equal(cut.sourceRegionId,'s1');
assert.equal(c.clipFromSection({start:4,end:null}),null);
const owner='あなたと';
const original={id:'lyric-line:abc',kind:'lyric-line',song:owner,workId:'w',textVersionId:'v',lineIndex:2,start:80,end:89,sourceText:'変更禁止'};
const prior={id:'song-section:x:intro',song:owner,kind:'song-section',sectionType:'intro',start:0,end:19,status:'draft'};
const arr={id:c.recordId(owner,'music-structure','test'),song:owner,kind:'music-structure',type:'chorus',label:'サビ',start:80.79,end:118.53,status:'confirmed',source:'manual',note:'',deleted:false};
const clip={id:c.recordId(owner,'short-cut','test'),song:owner,kind:'short-cut',label:'サビ',start:85,end:106,status:'draft',sourceRegionId:arr.id};
const entries=[original,prior,arr,clip];
const before=JSON.stringify(entries);
const doc=c.exportPlan(owner,entries,new Date('2026-11-23T00:00:00Z'));
assert.equal(doc.sections.length,1);
assert.equal(doc.shortCandidates.length,1);
assert.equal(doc.existingInstrumentalSections.length,1);
assert.equal(doc.shortCandidates[0].sourceRegionId,arr.id);
assert.equal(JSON.stringify(entries),before);
assert.equal(doc.sections[0].duration,37.74);
assert.equal(doc.shortCandidates[0].status,'draft');
assert.deepEqual(Array.from(c.overlapWarnings([arr],{song:owner,start:90,end:94,label:'重複'})),['サビ']);
assert.equal(c.isArrangement(arr,owner),true);
assert.equal(c.isShort(clip,owner),true);
assert.equal(c.isArrangement(prior,owner),false);
assert.ok(!c.isShort({...clip,deleted:true},owner));
assert.ok(!c.isArrangement({...arr,syncConflictOf:arr.id},owner));
assert.ok(widget.includes("kind:mode"));
assert.ok(widget.includes("lineIndex:mode==='music-structure'?-10000:-20000"));
assert.ok(widget.includes("core.recordId(song,mode,uid())"));
assert.ok(widget.includes("if(r&&conflicts(r.id).length)"));
assert.ok(widget.includes("function saveFormDraft()"));
assert.ok(widget.includes("sourceRegionId:mode==='short-cut'"));
assert.ok(widget.includes("ssImport"));
assert.ok(widget.includes("ssMakeShort"));
assert.ok(widget.includes("ssExport"));
assert.ok(widget.includes("ssCaptureStart"));
assert.ok(widget.includes("ssPreview"));
assert.ok(!widget.includes("writeRevision"));
assert.ok(!widget.includes("lyric_master_text_versions"));
assert.match(html,/full-song-sync\.js\?v=16[\s\S]*?song-structure-core\.js\?v=19\.0[\s\S]*?song-structure-studio\.js\?v=19\.0/);
assert.match(html,/song-structure-studio\.css\?v=19\.0/);
assert.ok(css.includes('#syncStudio.syncArrangementActive #syncLines'));
console.log('REC NOTE v19 music structure/short plan: PASS. 19 section suggestions, 6 short suggestions; lyrics untouched.');
